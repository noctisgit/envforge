# ---- scale (opt-in: pytest -m slow) --------------------------------------------------------


def _write_big_jsonl(path: Path, n: int, seed: int = 0) -> None:
    """~1 KB per conversation; written incrementally (never held in memory)."""
    rng = random.Random(seed)
    topics = list(TOPICS.values())
    with path.open("w", encoding="utf-8") as f:
        for i in range(n):
            t = topics[i % len(topics)]
            msgs = [
                {"role": "customer", "content": f"{rng.choice(t['open'])}, order {rng.randint(10**5, 10**6)}. {rng.choice(t['detail'])}."},
                {"role": "agent", "content": f"Thanks for contacting us. {rng.choice(t['agent'])}. Reference {rng.randint(1000, 9999)}."},
                {"role": "customer", "content": f"{rng.choice(t['detail'])} about {rng.randint(2, 59)} minutes ago, and {rng.choice(t['detail'])}."},
                {"role": "agent", "content": f"{rng.choice(t['agent'])}. {rng.choice(t['close'])}."},
                {"role": "customer", "content": f"ok. {rng.choice(t['open'])}. Email me at user{i}@example.com"},
                {"role": "agent", "content": f"{rng.choice(t['close'])}. Case {rng.randint(10, 99)}. Have a good day."},
            ]  # fmt: skip
            f.write(json.dumps({"id": f"c{i}", "messages": msgs}) + "\n")
            if i % 50 == 0 and i:  # some exact duplicates
                f.write(json.dumps({"id": f"dup{i}", "messages": msgs}) + "\n")


@pytest.mark.slow
def test_scale_200k_bounded_memory(tmp_path):
    pytest.importorskip("sklearn")
    n = 200_000
    src = tmp_path / "big.jsonl"
    _write_big_jsonl(src, n)
    size_mb = src.stat().st_size / 1e6
    timings: dict[str, float] = {}
    tracemalloc.start()
    t0 = time.monotonic()
    with C.CorpusStore(tmp_path / "corpus.sqlite") as store:
        report = C.ingest_file_to_store(src, store, "big", workers=4, batch_size=2000)
        timings["ingest"] = time.monotonic() - t0
        _, peak_ingest = tracemalloc.get_traced_memory()
        tracemalloc.reset_peak()
        t = time.monotonic()
        dd = C.dedupe_near(store)
        timings["dedupe"] = time.monotonic() - t
        _, peak_dedupe = tracemalloc.get_traced_memory()
        tracemalloc.reset_peak()
        t = time.monotonic()
        infos = C.cluster(store, seed=0)
        timings["cluster"] = time.monotonic() - t
        _, peak_cluster = tracemalloc.get_traced_memory()
        t = time.monotonic()
        ids = C.stratified_sample(store, 50, seed=0)
        ov = C.overview(store)
        timings["sample+overview"] = time.monotonic() - t
    tracemalloc.stop()
    peaks = {"ingest": peak_ingest, "dedupe": peak_dedupe, "cluster": peak_cluster}
    print(
        f"\n{n} conversations, {size_mb:.0f} MB: "
        + ", ".join(f"{k} {v:.1f}s" for k, v in timings.items())
        + " | peak traced MB: "
        + ", ".join(f"{k} {v / 1e6:.0f}" for k, v in peaks.items())
        + f" | clusters {len(infos)} | dups {dd.duplicates}"
    )
    assert report.conversations == n + (n - 1) // 50
    assert report.exact_duplicates == (n - 1) // 50
    assert ov["conversations"] == report.conversations and len(ids) == 50
    assert max(peaks.values()) < 400e6  # bounded: the corpus itself is ~200 MB+
    assert timings["ingest"] < 900
