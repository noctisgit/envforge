@pytest.mark.parametrize("fmt", ["jsonl", "csv", "txt"])
def test_ingest_streams_redacts_and_finds_exact_dups(tmp_path, fmt):
    convs, truth = make_corpus(12, dups=6, near=0)
    path = WRITERS[fmt](tmp_path / f"chats.{fmt}", convs)
    events: list[C.IngestProgress] = []
    db = tmp_path / "corpus.sqlite"
    with C.CorpusStore(db) as store:
        report = C.ingest_file_to_store(
            path, store, "up1", batch_size=17, on_progress=events.append
        )
        assert report.conversations == len(convs) == store.count()
        assert report.exact_duplicates == 6
        assert store.count(unique_only=True) == len(convs) - 6
        assert report.pii_counts.get("EMAIL", 0) >= 1 and report.pii_counts.get("CARD", 0) >= 1
        # progress: once per batch (and at the end), never going backwards
        assert len(events) >= len(convs) // 17
        assert [e.conversations for e in events] == sorted(e.conversations for e in events)
        assert events[-1].fraction == 1.0
        # exact copies point at their original
        for cid, t in truth.items():
            if t["kind"] == "exact":
                row = store.db.execute(
                    "SELECT near_dup_of FROM conversations WHERE id = ?", (f"up1:{cid}",)
                ).fetchone()
                assert row[0] == f"up1:{t['dup_of']}"
        conv = store.get([f"up1:{next(iter(truth))}"])[0]
        assert conv.meta["redacted"] and conv.meta["upload_id"] == "up1"
        assert store.uploads()[0]["upload_id"] == "up1"
    assert_no_pii(store_bytes(db))


def test_ingest_parallel_redaction_is_deterministic(tmp_path):
    convs, _ = make_corpus(20, dups=0, near=0)
    path = write_jsonl(tmp_path / "c.jsonl", convs)
    dumps = []
