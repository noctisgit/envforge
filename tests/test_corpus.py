@pytest.mark.parametrize("fmt", ["jsonl", "csv", "txt"])
def test_iter_conversations_matches_parse_file(tmp_path, fmt):
    convs, _ = make_corpus(6, dups=0, near=0)
    path = WRITERS[fmt](tmp_path / f"chats.{fmt}", convs)
    expected = parse_file(path).conversations
    stream = iter_conversations(path, window=3)
    got = list(stream)
    assert [c.to_dict() for c in got] == [c.to_dict() for c in expected]
    assert stream.done and stream.bytes_read == stream.bytes_total
    assert stream.conversations == len(convs)


def test_stream_reads_lazily(tmp_path):
    convs, _ = make_corpus(400, dups=0, near=0)  # ~2000 conversations, ~1.5 MB
    path = write_jsonl(tmp_path / "big.jsonl", convs)
