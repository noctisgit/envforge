def _purity(store: C.CorpusStore, truth: dict[str, dict[str, Any]]) -> float:
    by_cluster: dict[int, Counter[str]] = {}
    for cid, cl in store.db.execute(
        "SELECT ext_id, cluster FROM conversations WHERE near_dup_of IS NULL"
    ):
        by_cluster.setdefault(cl, Counter())[truth[cid]["topic"]] += 1
    total = sum(sum(c.values()) for c in by_cluster.values())
    return sum(c.most_common(1)[0][1] for c in by_cluster.values()) / total


def test_cluster_recovers_topics(built):
    store, truth, _, _, infos = built
    unique = store.count(unique_only=True)
    assert len(infos) == C.auto_k(unique)
    assert sum(i.size for i in infos) == unique
    assert [i.size for i in infos] == sorted((i.size for i in infos), reverse=True)
    assert _purity(store, truth) >= 0.95
    for info in infos:
        assert info.label and info.top_terms and 1 <= len(info.examples) <= 5
        cl = {c.meta["cluster"] for c in store.get(info.examples)}
        assert cl == {info.cluster}
    # duplicates sit in their original's cluster
    rows = store.db.execute(
        "SELECT d.cluster, o.cluster FROM conversations d JOIN conversations o "
        "ON o.id = d.near_dup_of"
    ).fetchall()
    assert rows and all(a == b for a, b in rows)
    assert "clusters" not in store.stale()


