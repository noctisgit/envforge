def test_failed_ingest_leaves_no_partial_upload(tmp_path):
    convs, _ = make_corpus(5, dups=0, near=0)
    path = write_jsonl(tmp_path / "c.jsonl", convs)
    calls = 0

    def flaky(conv):
        nonlocal calls
        calls += 1
        if calls == 12:
            raise RuntimeError("redactor crashed")
        return C.redact_conversation(conv)

    with C.CorpusStore(tmp_path / "s.sqlite") as store:
        with pytest.raises(RuntimeError):
            C.ingest_file_to_store(path, store, "u", redact=flaky, batch_size=5)
        assert store.count() == 0 and store.uploads() == []


def test_repeated_ids_are_renamed_and_reingest_replaces(tmp_path):
    a = {"id": "same", "messages": [{"role": "customer", "content": "router broken"}]}
    other = {"id": "other", "messages": [{"role": "customer", "content": "parcel late"}]}
    b = {"id": "same", "messages": [{"role": "customer", "content": "invoice wrong"}]}
    path = write_jsonl(tmp_path / "c.jsonl", [a, other, b])  # "same" twice, far apart
    with C.CorpusStore(tmp_path / "s.sqlite") as store:
        r = C.ingest_file_to_store(path, store, "u1", stream_window=1)
        assert r.renamed == 1
        assert sorted(store.iter_ids()) == ["u1:other", "u1:same", "u1:same#2"]
        C.ingest_file_to_store(path, store, "u1", stream_window=1)  # a retry replaces
        assert store.count() == 3
        C.ingest_file_to_store(path, store, "u2", stream_window=1)  # same file, new upload
        assert store.count() == 6 and store.count(unique_only=True) == 3
        assert store.delete_upload("u1") == 3
        assert store.count() == 3 and store.count(unique_only=True) == 3  # u2 now original
        assert "dedupe" in store.stale()


