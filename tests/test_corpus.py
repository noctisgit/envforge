def test_allocate_proportions_minimums_and_caps():
    sizes = {0: 600, 1: 300, 2: 90, 3: 10}
    # 1 each first, then the other 96 by size (57.6 / 28.8 / 8.64 / 0.96 -> largest
    # remainders get the last 3)
    assert C.allocate(100, sizes) == {0: 58, 1: 30, 2: 10, 3: 2}
    assert C.allocate(2, sizes) == {0: 1, 1: 1, 2: 0, 3: 0}  # n < clusters: the largest
    capped = C.allocate(100, sizes, cap=30)
    assert capped[0] == 30 and capped[1] == 30 and capped[2] == 30 and capped[3] == 10
    assert sum(C.allocate(10_000, sizes).values()) == 1000  # can't exceed what exists


