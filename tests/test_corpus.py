# personal data planted in some conversations: none of it may reach the store
PII_NAME = "Bartholomew Quackenbush"
PII_CARD = "4111 1111 1111 1111"


def _pii_email(i: int) -> str:
    return f"customer{i}.secret@example.com"


def _pii_phone(i: int) -> str:
    return f"+44 20 7946 {1000 + i % 9000:04d}"


def make_corpus(per_topic: int = 40, *, seed: int = 0, dups: int = 10, near: int = 10):
    """Conversations as dicts ({"id", "messages": [{"role", "content"}]}) plus truth.

    Returns (conversations, truth) where truth maps id -> {"topic", "dup_of", "kind"}.
    Planted copies come right after the base conversations: `dups` exact duplicates
    (same text, different id and whitespace) and `near` near-duplicates (a word added
    at the end: Jaccard similarity ~0.98).
    """
    rng = random.Random(seed)
    convs: list[dict[str, Any]] = []
    truth: dict[str, dict[str, Any]] = {}
    i = 0
    for _round in range(per_topic):
        for topic, t in TOPICS.items():
            i += 1
            cid = f"T{i:05d}"
            order_no = rng.randint(100000, 999999)
            minutes = rng.randint(2, 59)
            ref = rng.randint(1000, 9999)
            first = f"{rng.choice(t['open'])}, order {order_no}."
            if i % 7 == 0:
                first += f" My name is {PII_NAME}, email {_pii_email(i)}."
            if i % 11 == 0:
                first += f" Call me on {_pii_phone(i)}."
            if i % 13 == 0:
                first += f" My card is {PII_CARD}."
            msgs = [
                {"role": "customer", "content": first},
                {"role": "agent", "content": "Thanks for contacting us. Let me take a look."},
                {"role": "customer", "content": f"{rng.choice(t['detail'])} about {minutes} minutes ago."},
                {"role": "agent", "content": f"{rng.choice(t['agent'])}. Reference {ref}."},
                {"role": "customer", "content": f"ok, {rng.choice(t['detail'])}"},
                {"role": "agent", "content": f"{rng.choice(t['close'])}. Case {rng.randint(10, 99)}."},
            ]  # fmt: skip
            convs.append({"id": cid, "messages": msgs})
            truth[cid] = {"topic": topic, "dup_of": None, "kind": "base"}
    base = list(convs)
    for j in range(dups):
        src = base[rng.randrange(len(base))]
        cid = f"D{j:04d}"
        msgs = [{**m, "content": "  " + m["content"] + " \t"} for m in src["messages"]]
        convs.append({"id": cid, "messages": msgs})
        truth[cid] = {"topic": truth[src["id"]]["topic"], "dup_of": src["id"], "kind": "exact"}
    for j in range(near):
        src = base[rng.randrange(len(base))]
        cid = f"N{j:04d}"
        last = src["messages"][-1]
        msgs = [*src["messages"][:-1], {**last, "content": last["content"] + " Thanks!"}]
        convs.append({"id": cid, "messages": msgs})
        truth[cid] = {"topic": truth[src["id"]]["topic"], "dup_of": src["id"], "kind": "near"}
    return convs, truth


def write_jsonl(path: Path, convs: list[dict[str, Any]]) -> Path:
    with path.open("w", encoding="utf-8") as f:
        for c in convs:
            f.write(json.dumps(c) + "\n")
    return path


def write_csv(path: Path, convs: list[dict[str, Any]]) -> Path:
    """One row per message (conversation_id, role, text)."""
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["conversation_id", "role", "text"])
        for c in convs:
            for m in c["messages"]:
                w.writerow([c["id"], m["role"], m["content"]])
    return path


def write_txt(path: Path, convs: list[dict[str, Any]]) -> Path:
    """Transcripts with "Conversation <id>" headers."""
    with path.open("w", encoding="utf-8") as f:
        for c in convs:
            f.write(f"Conversation {c['id']}\n")
            for m in c["messages"]:
                f.write(f"{m['role'].capitalize()}: {m['content']}\n")
            f.write("\n")
    return path


WRITERS = {"jsonl": write_jsonl, "csv": write_csv, "txt": write_txt}


def store_bytes(path: Path) -> bytes:
    """Everything SQLite has on disk for this store (main file + WAL, if any)."""
    data = path.read_bytes()
    for extra in (Path(f"{path}-wal"), Path(f"{path}-journal")):
        if extra.exists():
            data += extra.read_bytes()
    return data


def assert_no_pii(data: bytes) -> None:
    text = data.decode("utf-8", errors="replace").lower()
    assert "quackenbush" not in text
    assert "@example.com" not in text
    assert PII_CARD not in text and PII_CARD.replace(" ", "") not in text
    assert "7946" not in text  # the phone numbers' fixed part


