    assert len(ids) == len(set(ids)) == 30
    assert ids == C.stratified_sample(store, 30, seed=1)  # deterministic
    assert ids != C.stratified_sample(store, 30, seed=2)
    got = store.get(ids)
    assert all(truth[c.meta["ext_id"]]["dup_of"] is None for c in got)  # no duplicates
    per_cluster = Counter(c.meta["cluster"] for c in got)
    assert set(per_cluster) == {i.cluster for i in infos}  # every cluster represented
    # proportional: the biggest cluster gets at least as many as the smallest
    assert per_cluster[infos[0].cluster] >= per_cluster[infos[-1].cluster]
    # the first len(infos) ids cover distinct clusters (round-robin interleaving)
    first = [c.meta["cluster"] for c in store.get(ids[: len(infos)])]
    assert len(set(first)) == len(infos)
    # caps and exclusions
    capped = C.stratified_sample(store, 30, per_cluster_cap=2, seed=1)
    assert max(Counter(c.meta["cluster"] for c in store.get(capped)).values()) <= 2
    rest = C.stratified_sample(store, 1000, exclude_ids=ids, seed=1)
    assert not set(rest) & set(ids)
    assert len(rest) == store.count(unique_only=True) - 30


